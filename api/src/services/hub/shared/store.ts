/**
 * Nivaro Hub phase 6: shared deployments (one process serving many apps, run by the Hub).
 *
 * The deployment token authorises the deployment calling the Hub (its tenants list). It is
 * generated by the Hub, shown once, and stored sealed (`token`) with its SHA-256 `token_lookup`;
 * a hit is confirmed by opening the seal and comparing timing-safe (as link-token.ts). On
 * rotation the previous token is kept sealed in `prev_token` (+ lookup) and stays valid until
 * `prev_token_until` (24 h), so a deployment still holding it keeps working while the new one
 * rolls out, and the Hub can call the deployment link with it during that grace (preflight R7).
 *
 * The Hub never sends the token itself to the deployment link: the link bearer is
 * `deploymentLinkBearer(token)` = HMAC-SHA256 keyed by the token over 'nivaro-deployment-link'
 * (hex), computed by both sides, so a sniffed link call never opens the tenants list.
 *
 * An app's ENCRYPTION_KEY (the key its sealed values were written with) is stored sealed on its
 * environment (`encryption_key`, an admin entry) with `encryption_key_fp` = keyFingerprint(key)
 * (preflight M4 names the columns). openAppKey reads it, else the Docker stack settings secret.
 *
 * Hub-only (HUB=on, never cloud mode). No value here is ever logged.
 */

const TABLE = 'nivaro_hub_shared_deployments'
const ENVS = 'nivaro_hub_environments'
const PLACEMENTS = 'nivaro_hub_placements'
const SHARED_DEPLOYS = 'nivaro_hub_shared_deploys'
const DRIVERS = 'nivaro_hub_drivers'

/** How long a rotated-out token keeps working. */
export const PREV_TOKEN_GRACE_MS = 24 * 60 * 60_000
/** Longer than any token anyone would type; refuses junk before any hashing or query. */
const MAX_TOKEN_LENGTH = 1024

export type SharedMode = 'registered' | 'docker'
export type SharedStatus = 'new' | 'active' | 'upgrading' | 'retired'
const MODES: readonly SharedMode[] = ['registered', 'docker']
const STATUSES: readonly SharedStatus[] = ['new', 'active', 'upgrading', 'retired']

export interface SharedDeployment {
  id: number
  key: string
  name: string
  mode: SharedMode
  driver_id: number | null
  stack: string | null
  version_pin: string | null
  extensions: string[]
  extension_pins: Record<string, string>
  host_pattern: string | null
  link_url: string
  pool_budget: number
  status: SharedStatus
  settings: Record<string, unknown>
  /** HUB_MASK when a token is stored, else null; never the token. */
  token: string | null
  last_seen_at: string | null
  created_at: string | null
  updated_at: string | null
}

/** What a create or update writes (validated). */
export interface SharedFields {
  key: string
  name: string
  mode: SharedMode
  driver_id: number | null
  stack: string | null
  version_pin: string | null
  extensions: string[]
  extension_pins: Record<string, string>
  host_pattern: string | null
  link_url: string
  pool_budget: number
  settings: Record<string, unknown>
}

export type SharedCode =
  | 'BAD_KEY'
  | 'KEY_TAKEN'
  | 'BAD_NAME'
  | 'BAD_LINK_URL'
  | 'BAD_PATTERN'
  | 'BAD_BUDGET'
  | 'BAD_EXTENSIONS'
  | 'DRIVER_NOT_DOCKER'
  | 'SHARED_IN_USE'
  // Added beside the plan's list: an unknown mode, a bad stack name / version pin / settings
  // object, a key or mode change on an existing deployment, a missing row.
  | 'BAD_MODE'
  | 'BAD_STACK'
  | 'BAD_VERSION'
  | 'BAD_SETTINGS'
  | 'IMMUTABLE'
  | 'NOT_FOUND'

const STATUS_OF: Partial<Record<SharedCode, number>> = {
  KEY_TAKEN: 409,
  SHARED_IN_USE: 409,
  NOT_FOUND: 404
}

/** A refusal from the store: `{statusCode, code, message}` (plain words, never a value). */
export class SharedError extends Error {
  code: SharedCode
  statusCode: number
  constructor(code: SharedCode, message: string, statusCode?: number) {
    super(message)
    this.name = 'SharedError'
    this.code = code
    this.statusCode = statusCode ?? STATUS_OF[code] ?? 400
  }
}

// ── validation ──────────────────────────────────────────────────────────────────────────────

const EXT_ID_RE = /^[a-z0-9-]{1,64}$/
const MAX_EXTENSIONS = 50
const PATTERN_RE = /^\*\.[a-z0-9-]+(\.[a-z0-9-]+)+$/
/** A version or image tag: what a pin may hold (no spaces, ≤ 64). */
const VERSION_PIN_RE = /^[0-9A-Za-z][0-9A-Za-z._+-]{0,63}$/
const SETTINGS_MAX = 20_000

type Fail = { ok: false; code: SharedCode; message: string }
const fail = (code: SharedCode, message: string): Fail => ({ ok: false, code, message })

function isPlainObject(v: unknown): v is Record<string, unknown> {
  return !!v && typeof v === 'object' && !Array.isArray(v)
}

function checkExtensions(v: unknown): string[] | null {
  if (v === undefined || v === null) return []
  if (!Array.isArray(v) || v.length > MAX_EXTENSIONS) return null
  const out: string[] = []
  for (const id of v) {
    if (typeof id !== 'string' || !EXT_ID_RE.test(id)) return null
    if (!out.includes(id)) out.push(id)
  }
  return out
}

function checkPins(v: unknown, extensions: string[]): Record<string, string> | null {
  if (v === undefined || v === null) return {}
  if (!isPlainObject(v)) return null
  const out: Record<string, string> = {}
  for (const [id, pin] of Object.entries(v)) {
    if (!extensions.includes(id)) return null
    if (typeof pin !== 'string' || !VERSION_PIN_RE.test(pin)) return null
    out[id] = pin
  }
  return out
}

/** The default stack name for a docker deployment: its key, cut to the stack-name rule. */
function defaultStack(key: string): string {
  return key.slice(0, 41).replace(/-+$/, '')
}

/**
 * Checks a create (no `existing`) or an update (`existing`: absent fields keep their value).
 * Key and mode never change on an existing deployment (IMMUTABLE). `ctx.driverKind` is the
 * named driver's kind when the caller has read it; createShared / updateShared always check it.
 */
export function validateSharedInput(
  input: unknown,
  existing?: SharedDeployment,
  ctx?: { driverKind?: string | null }
): Validation<SharedFields, SharedCode> {
  const body = isPlainObject(input) ? input : {}
  const has = (k: string) => Object.hasOwn(body, k) && body[k] !== undefined
  const pick = (k: keyof SharedFields): unknown =>
    has(k) ? body[k] : existing ? existing[k] : undefined

  const key = pick('key')
  if (existing && has('key') && body.key !== existing.key)
    return fail('IMMUTABLE', 'A shared deployment keeps its key; add a new one instead.')
  if (!isHubKey(key))
    return fail(
      'BAD_KEY',
      'The key is 2–63 characters: lower-case letters, digits and hyphens, starting with a letter.'
    )

  const rawName = pick('name')
  const name = typeof rawName === 'string' ? rawName.trim() : ''
  if (!name || name.length > 200)
    return fail('BAD_NAME', 'A shared deployment needs a name of at most 200 characters.')

  const mode = pick('mode') ?? 'registered'
  if (existing && has('mode') && body.mode !== existing.mode)
    return fail('IMMUTABLE', 'A shared deployment keeps its mode; add a new one instead.')
  if (!(MODES as readonly unknown[]).includes(mode))
    return fail('BAD_MODE', 'The mode is registered or docker.')

  let driverId: number | null = null
  let stack: string | null = null
  if (mode === 'docker') {
    const d = pick('driver_id')
    const n = typeof d === 'number' ? d : typeof d === 'string' ? Number(d) : Number.NaN
    if (!Number.isInteger(n) || n < 1 || n > 2147483647)
      return fail('DRIVER_NOT_DOCKER', 'A docker shared deployment needs a Docker driver.')
    if (ctx?.driverKind !== undefined && ctx.driverKind !== 'docker')
      return fail('DRIVER_NOT_DOCKER', 'A docker shared deployment needs a Docker driver.')
    driverId = n
    const s = pick('stack') ?? defaultStack(key)
    if (typeof s !== 'string' || !STACK_NAME_RE.test(s))
      return fail(
        'BAD_STACK',
        'The stack name is 2–41 characters: lower-case letters, digits and hyphens, starting with a letter.'
      )
    stack = s
  }

  const pin = pick('version_pin')
  if (pin !== undefined && pin !== null && (typeof pin !== 'string' || !VERSION_PIN_RE.test(pin)))
    return fail(
      'BAD_VERSION',
      'The version pin is a version or image tag of at most 64 characters.'
    )

  const extensions = checkExtensions(pick('extensions'))
  if (!extensions)
    return fail(
      'BAD_EXTENSIONS',
      `Extensions are a list of at most ${MAX_EXTENSIONS} ids (lower-case letters, digits and hyphens).`
    )
  const pins = checkPins(pick('extension_pins'), extensions)
  if (!pins)
    return fail(
      'BAD_EXTENSIONS',
      'Extension pins name a listed extension and a version of at most 64 characters.'
    )

  const pattern = pick('host_pattern')
  const hostPattern = pattern === undefined || pattern === null || pattern === '' ? null : pattern
  if (
    hostPattern !== null &&
    (typeof hostPattern !== 'string' || hostPattern.length > 253 || !PATTERN_RE.test(hostPattern))
  )
    return fail(
      'BAD_PATTERN',
      'The host pattern is a wildcard name such as *.apps.example.com (lower case).'
    )

  const link = agentOrigin(pick('link_url'))
  if (!link)
    return fail(
      'BAD_LINK_URL',
      'The link URL is an https origin with no credentials or path (http only for loopback or private addresses).'
    )

  const budget = pick('pool_budget') ?? 60
  if (typeof budget !== 'number' || !Number.isInteger(budget) || budget < 1 || budget > 500)
    return fail('BAD_BUDGET', 'The pool budget is a whole number from 1 to 500.')

  const settings = pick('settings') ?? {}
  if (!isPlainObject(settings) || JSON.stringify(settings).length > SETTINGS_MAX)
    return fail('BAD_SETTINGS', 'Settings are an object of at most 20,000 characters.')

  return {
    ok: true,
    row: {
      key,
      name,
      mode: mode as SharedMode,
      driver_id: driverId,
      stack,
      version_pin: (pin as string | null | undefined) ?? null,
      extensions,
      extension_pins: pins,
      host_pattern: hostPattern as string | null,
      link_url: link,
      pool_budget: budget,
      settings
    }
  }
}

// ── rows ────────────────────────────────────────────────────────────────────────────────────

function jsonOf<T>(raw: unknown, fallback: T, ok: (v: unknown) => boolean): T {
  if (raw === null || raw === undefined || raw === '') return fallback
  try {
    const v = typeof raw === 'string' ? JSON.parse(raw) : raw
    return ok(v) ? (v as T) : fallback
  } catch {
    return fallback
  }
}

function iso(v: unknown): string | null {
  if (v === null || v === undefined || v === '') return null
  // SQLite may hand a datetime back as epoch milliseconds.
  const d =
    v instanceof Date
      ? v
      : typeof v === 'number' || /^\d{12,}$/.test(String(v))
        ? new Date(Number(v))
        : new Date(String(v))
  return Number.isNaN(d.getTime()) ? String(v) : d.toISOString()
}

function timeOf(v: unknown): number | null {
  const s = iso(v)
  if (!s) return null
  const t = new Date(s).getTime()
  return Number.isNaN(t) ? null : t
}

export function sharedFromRow(r: Record<string, unknown>): SharedDeployment {
  const extensions = jsonOf<string[]>(
    r.extensions,
    [],
    (v) => Array.isArray(v) && v.every((x) => typeof x === 'string')
  )
  const status = String(r.status ?? 'new') as SharedStatus
  return {
    id: Number(r.id),
    key: String(r.key),
    name: String(r.name),
    mode: r.mode === 'docker' ? 'docker' : 'registered',
    driver_id: r.driver_id == null ? null : Number(r.driver_id),
    stack: r.stack == null ? null : String(r.stack),
    version_pin: r.version_pin == null ? null : String(r.version_pin),
    extensions,
    extension_pins: jsonOf<Record<string, string>>(r.extension_pins, {}, isPlainObject),
    host_pattern: r.host_pattern == null ? null : String(r.host_pattern),
    link_url: String(r.link_url),
    pool_budget: Number(r.pool_budget ?? 60),
    status: STATUSES.includes(status) ? status : 'new',
    settings: jsonOf<Record<string, unknown>>(r.settings, {}, isPlainObject),
    token: maskSecret((r.token as string | null) ?? null),
    last_seen_at: iso(r.last_seen_at),
    created_at: iso(r.created_at),
    updated_at: iso(r.updated_at)
  }
}

/** The columns a read selects: never the sealed ones beyond `token` (masked on the way out). */
const READ_COLS = [
  'id',
  'key',
  'name',
  'mode',
  'driver_id',
  'stack',
  'version_pin',
  'extensions',
  'extension_pins',
  'host_pattern',
  'link_url',
  'pool_budget',
  'status',
  'settings',
  'token',
  'last_seen_at',
  'created_at',
  'updated_at'
]

function writeCols(f: Partial<SharedFields>): Record<string, unknown> {
  const out: Record<string, unknown> = {}
  if (f.key !== undefined) out.key = f.key
  if (f.name !== undefined) out.name = f.name
  if (f.mode !== undefined) out.mode = f.mode
  if (f.driver_id !== undefined) out.driver_id = f.driver_id
  if (f.stack !== undefined) out.stack = f.stack
  if (f.version_pin !== undefined) out.version_pin = f.version_pin
  if (f.extensions !== undefined) out.extensions = JSON.stringify(f.extensions)
  if (f.extension_pins !== undefined) out.extension_pins = JSON.stringify(f.extension_pins)
  if (f.host_pattern !== undefined) out.host_pattern = f.host_pattern
  if (f.link_url !== undefined) out.link_url = f.link_url
  if (f.pool_budget !== undefined) out.pool_budget = f.pool_budget
  if (f.settings !== undefined) out.settings = JSON.stringify(f.settings)
  return out
}

export async function listShared(): Promise<SharedDeployment[]> {
  const rows = (await db(TABLE).select(READ_COLS).orderBy('id')) as Record<string, unknown>[]
  return rows.map(sharedFromRow)
}

export async function getShared(id: number): Promise<SharedDeployment | null> {
  const row = await db(TABLE).where({ id }).first(READ_COLS)
  return row ? sharedFromRow(row) : null
}

export async function getSharedByKey(key: string): Promise<SharedDeployment | null> {
  if (!isHubKey(key)) return null
  const row = await db(TABLE).where({ key }).first(READ_COLS)
  return row ? sharedFromRow(row) : null
}

/** Throws DRIVER_NOT_DOCKER unless a docker deployment names an existing Docker driver. */
async function assertDriver(f: Pick<SharedFields, 'mode' | 'driver_id'>): Promise<void> {
  if (f.mode !== 'docker') return
  const d = f.driver_id ? await db(DRIVERS).where({ id: f.driver_id }).first('kind') : null
  if (d?.kind !== 'docker')
    throw new SharedError('DRIVER_NOT_DOCKER', 'A docker shared deployment needs a Docker driver.')
}

/** A new deployment token: 32 random bytes, base64url (43 characters). */
function newToken(): string {
  return randomBytes(32).toString('base64url')
}

function isUniqueViolation(err: unknown): boolean {
  const e = err as { code?: unknown; number?: unknown; errno?: unknown; message?: unknown }
  const code = String(e?.code ?? '')
  return (
    code === '23505' || // postgres
    code === 'ER_DUP_ENTRY' || // mysql / mariadb
    code.startsWith('SQLITE_CONSTRAINT') ||
    e?.number === 2627 ||
    e?.number === 2601 || // sql server
    /unique|duplicate/i.test(String(e?.message ?? ''))
  )
}

const keyTaken = () =>
  new SharedError('KEY_TAKEN', 'Another shared deployment already uses this key.')

/** Stores a validated deployment. The token is answered once and never again. */
export async function createShared(
  f: SharedFields,
  by: string | null
): Promise<{ row: SharedDeployment; token: string }> {
  await assertDriver(f)
  if (await db(TABLE).where({ key: f.key }).first('id')) throw keyTaken()
  const token = newToken()
  let id: string | number | null
  try {
    id = await insertReturningId(db, TABLE, {
      ...writeCols(f),
      status: 'new',
      token: sealSecret(token),
      token_lookup: tokenLookupHash(token),
      created_by: by,
      created_at: new Date(),
      updated_at: new Date()
    })
  } catch (err) {
    // Never rethrow the engine's error: knex inlines bindings (the sealed token) into it.
    if (isUniqueViolation(err)) throw keyTaken()
    throw new Error('Saving the shared deployment failed')
  }
  const row = id == null ? await getSharedByKey(f.key) : await getShared(Number(id))
  if (!row) throw new Error('shared deployment vanished after save')
  return { row, token }
}

/**
 * Writes the given (validated) fields; null when there is no such deployment. Key and mode are
 * checked by validateSharedInput (IMMUTABLE); a docker driver is checked again here.
 */
export async function updateShared(
  id: number,
  f: Partial<SharedFields>
): Promise<SharedDeployment | null> {
  const existing = await getShared(id)
  if (!existing) return null
  if (f.mode !== undefined || f.driver_id !== undefined)
    await assertDriver({
      mode: f.mode ?? existing.mode,
      driver_id: f.driver_id !== undefined ? f.driver_id : existing.driver_id
    })
  const cols = writeCols(f)
  if (Object.keys(cols).length) {
    try {
      await db(TABLE)
        .where({ id })
        .update({ ...cols, updated_at: new Date() })
    } catch (err) {
      if (isUniqueViolation(err)) throw keyTaken()
      throw err
    }
  }
  return getShared(id)
}

/** Sets a deployment's status (the runners' writes). */
export async function setSharedStatus(id: number, status: SharedStatus): Promise<void> {
  await db(TABLE).where({ id }).update({ status, updated_at: new Date() })
}

/**
 * A new token; the current one becomes the previous one, valid for 24 h. The answer is the only
 * place the new token appears.
 */
export async function rotateSharedToken(id: number): Promise<{ token: string }> {
  const row = (await db(TABLE).where({ id }).first('id', 'token', 'token_lookup')) as
    | { id: number; token: string | null; token_lookup: string | null }
    | undefined
  if (!row) throw new SharedError('NOT_FOUND', 'No such shared deployment.')
  const token = newToken()
  await db(TABLE)
    .where({ id })
    .update({
      token: sealSecret(token),
      token_lookup: tokenLookupHash(token),
      prev_token: row.token,
      prev_token_lookup: row.token ? row.token_lookup : null,
      prev_token_until: row.token ? new Date(Date.now() + PREV_TOKEN_GRACE_MS) : null,
      updated_at: new Date()
    })
  return { token }
}

function sha256(v: string): Buffer {
  return createHash('sha256').update(v, 'utf8').digest()
}

/** True when the sealed value opens and equals `presented` (timing-safe over both hashes). */
function sealedMatches(sealed: string | null, presented: string): boolean {
  let plain: string | null
  try {
    plain = openSecret(sealed)
  } catch {
    return false
  }
  if (!plain) return false
  return timingSafeEqual(sha256(plain), sha256(presented))
}

/**
 * The deployment `key` whose token is `bearer` (the current one, or the previous one inside its
 * grace); null otherwise. Callers rate-limit failures (failedAuthLimiter) like hub-link.ts.
 */
export async function sharedForToken(
  key: string,
  bearer: string
): Promise<SharedDeployment | null> {
  if (!isHubKey(key)) return null
  if (typeof bearer !== 'string' || !bearer || bearer.length > MAX_TOKEN_LENGTH) return null
  const row = (await db(TABLE)
    .where({ key })
    .first([
      ...READ_COLS,
      'token_lookup',
      'prev_token',
      'prev_token_lookup',
      'prev_token_until'
    ])) as Record<string, unknown> | undefined
  if (!row) return null
  const lookup = tokenLookupHash(bearer)
  if (row.token_lookup === lookup && sealedMatches((row.token as string) ?? null, bearer))
    return sharedFromRow(row)
  const until = timeOf(row.prev_token_until)
  if (
    row.prev_token_lookup === lookup &&
    until !== null &&
    until > Date.now() &&
    sealedMatches((row.prev_token as string) ?? null, bearer)
  )
    return sharedFromRow(row)
  return null
}

/** Opens a sealed column; null when empty or unreadable (never throws a value). */
function openOrNull(sealed: unknown): string | null {
  try {
    return openSecret((sealed as string | null) ?? null)
  } catch {
    return null
  }
}

/** The deployment token in plain. Only runs call this (renderer, link client); never logged. */
export async function openSharedToken(id: number): Promise<string | null> {
  const row = await db(TABLE).where({ id }).first('token')
  return row ? openOrNull(row.token) : null
}

/** The previous token while its grace lasts, else null (the link client's retry on 401). */
export async function openSharedPrevToken(id: number): Promise<string | null> {
  const row = await db(TABLE).where({ id }).first('prev_token', 'prev_token_until')
  if (!row) return null
  const until = timeOf(row.prev_token_until)
  if (until === null || until <= Date.now()) return null
  return openOrNull(row.prev_token)
}

/**
 * The bearer the Hub sends to a deployment's link (preflight R7): HMAC-SHA256 keyed by the
 * deployment token over 'nivaro-deployment-link', hex. The deployment computes the same from its
 * HUB_DEPLOYMENT_TOKEN; the token itself never travels to the link.
 */
export function deploymentLinkBearer(token: string): string {
  return createHmac('sha256', token).update('nivaro-deployment-link').digest('hex')
}

/** Removes a deployment and its run history; SHARED_IN_USE while a placement names it. */
export async function deleteShared(id: number): Promise<void> {
  const used = await db(PLACEMENTS).where({ shared_deployment_id: id }).first('id')
  if (used)
    throw new SharedError(
      'SHARED_IN_USE',
      'Environments are placed on this shared deployment — move them off it first.'
    )
  await db.transaction(async (trx) => {
    await trx(SHARED_DEPLOYS).where({ shared_deployment_id: id }).del()
    await trx(TABLE).where({ id }).del()
  })
}

// ── tenants and app keys ────────────────────────────────────────────────────────────────────

/**
 * The tenant id of an environment on a shared deployment: the app key (first 48 characters) and
 * the environment id. The same across moves, never reused (environment ids are not).
 */
export function tenantIdFor(app: { key: string }, env: { id: number }): string {
  return `${app.key.slice(0, 48)}-e${env.id}`
}

/** Stores an app's ENCRYPTION_KEY on its environment, sealed, with its fingerprint. */
export async function setAppKey(envId: number, hexKey: string): Promise<{ fp: string }> {
  if (typeof hexKey !== 'string' || !APP_KEY_RE.test(hexKey))
    throw new SharedError(
      'BAD_KEY',
      "The app's encryption key is 64 hex characters (its ENCRYPTION_KEY)."
    )
  const key = hexKey.toLowerCase()
  const env = await db(ENVS).where({ id: envId }).first('id')
  if (!env) throw new SharedError('NOT_FOUND', 'No such environment.')
  const fp = keyFingerprint(key)
  await db(ENVS)
    .where({ id: envId })
    .update({ encryption_key: sealSecret(key), encryption_key_fp: fp, updated_at: new Date() })
  return { fp }
}

/**
 * The app's ENCRYPTION_KEY, or null when the Hub does not know it: the environment's own entry,
 * else its Docker stack settings secret (preflight R9; the phase-3 creation record never held
 * the key, so GitLab-created apps need an admin entry). Never logged or answered.
 */
export async function openAppKey(envId: number): Promise<string | null> {
  const env = await db(ENVS).where({ id: envId }).first('encryption_key')
  if (!env) return null
  const own = openOrNull(env.encryption_key)
  if (own && APP_KEY_RE.test(own)) return own.toLowerCase()
  let fromStack: string | undefined
  try {
    fromStack = openStackSecrets(await readStackSettings(envId)).ENCRYPTION_KEY
  } catch {
    return null
  }
  return fromStack && APP_KEY_RE.test(fromStack) ? fromStack.toLowerCase() : null
}
