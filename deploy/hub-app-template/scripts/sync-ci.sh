#!/bin/sh
# Writes ci/deploy.yml — the deploy job app repositories include from this template project at a
# pinned ref — with scripts/deploy.sh embedded verbatim (an included job cannot read files of
# the project it came from, and the app repository's own copy must never be what runs).
#
#   sh scripts/sync-ci.sh           rewrite ci/deploy.yml
#   sh scripts/sync-ci.sh --check   exit 1 when ci/deploy.yml is out of date
#
# After changing deploy.sh: run it, commit both, tag the commit, and point the Hub target's
# template_ref at the new tag.
set -eu
cd "$(dirname "$0")/.."

# CI job image: alpine/git 2.47.2 (sh, OpenSSH client, base64, sha256sum), pinned by digest.
# Re-pin with: docker buildx imagetools inspect alpine/git:<tag>   (the "Digest:" line)
IMAGE='alpine/git:2.47.2@sha256:062a01ad7a0eb17cff382bc5e26086b4d710e56dfdfdf001109a49b6d9bd378c'

if grep -qx 'HUB_DEPLOY_SH' scripts/deploy.sh; then
  echo "sync-ci: scripts/deploy.sh may not contain the line HUB_DEPLOY_SH" >&2
  exit 1
fi

render() {
  cat <<EOF
# GENERATED by scripts/sync-ci.sh from scripts/deploy.sh: edit those, then run it.
#
# The deploy job of every Nivaro Hub app repository. The Hub sets each app project's CI
# configuration path to this file in the Hub-owned template project at a pinned ref
# (ci/deploy.yml@<template project>:<tag or sha>), so the app repository's own .gitlab-ci.yml
# is never read. (That file, also written by the Hub, only includes this one: a fallback.)
#
# It runs on a push to a branch that holds .hub/app.env (main holds none), refuses a missing
# pin, a pin of latest and a pin without an image digest, then runs the embedded deploy.sh.

stages:
  - deploy

deploy:
  stage: deploy
  image:
    name: $IMAGE
    entrypoint: ['']
  environment:
    name: \$CI_COMMIT_REF_NAME
  # One deploy at a time per environment.
  resource_group: \$CI_COMMIT_REF_NAME
  interruptible: false
  variables:
    HUB_PIN_FILE: .hub/nivaro-version
  rules:
    - if: \$CI_COMMIT_BRANCH
      exists:
        - .hub/app.env
  script:
    - test -s "\$HUB_PIN_FILE" || { echo "no \$HUB_PIN_FILE pin, refusing to deploy"; exit 1; }
    - test "\$(sed -n 1p "\$HUB_PIN_FILE" | tr -d '[:space:]')" != latest || { echo "\$HUB_PIN_FILE pins latest, refusing"; exit 1; }
    - test -n "\$(sed -n 2p "\$HUB_PIN_FILE" | tr -d '[:space:]' | grep -E '^sha256:[0-9a-f]{64}\$')" || { echo "\$HUB_PIN_FILE line 2 must be the image digest, refusing"; exit 1; }
    - |
      f=\$(mktemp)
      cat >"\$f" <<'HUB_DEPLOY_SH'
EOF
  sed 's/^/      /; s/^ *$//' scripts/deploy.sh
  cat <<'EOF'
      HUB_DEPLOY_SH
      sh "$f"
EOF
}

if [ "${1:-}" = --check ]; then
  tmp=$(mktemp)
  render >"$tmp"
  if cmp -s "$tmp" ci/deploy.yml; then
    rm -f "$tmp"
    exit 0
  fi
  rm -f "$tmp"
  echo "sync-ci: ci/deploy.yml is out of date; run sh scripts/sync-ci.sh" >&2
  exit 1
fi
mkdir -p ci
render >ci/deploy.yml
echo "sync-ci: wrote ci/deploy.yml"
